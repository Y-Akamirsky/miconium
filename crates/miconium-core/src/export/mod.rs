#[derive(Debug, Error)]
pub enum ExportError {
    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),
    #[error("SVG assembly error: {0}")]
    Svg(#[from] svg_engine::SvgError),
    #[error("no frames available in pack")]
    NoFrames,
    #[error("symlink error: {0}")]
    Symlink(String),
    #[error("icon cache update failed: {0}")]
    CacheUpdate(String),
}

#[derive(Debug, Clone)]
pub struct ExportProgress {
    pub category: String,
    pub variant: String,
    pub current: usize,
    pub total: usize,
    pub message: String,
}

